// Package grip computes OpenPGP key grips: a 20-byte SHA-1 hash over a
// canonical Rivest S-Expression encoding of the public key parameters
// (https://datatracker.ietf.org/doc/draft-rivest-sexp/), used to identify
// keys independently of their on-disk representation.
package grip

import (
	"bytes"
	"crypto/sha1"
	"fmt"

	"github.com/malivvan/crypto/ed25519"
	"github.com/malivvan/crypto/x25519"
)

type rivestSExpPart struct {
	name  string
	value []byte
}

// computeRivestSExp computes Rivest's S-Expression for a given list of parts.
// https://datatracker.ietf.org/doc/draft-rivest-sexp/
func computeRivestSExp(parts []rivestSExpPart) *[20]byte {
	h := new(bytes.Buffer)
	for i := 0; i < len(parts); i++ {
		_, err := fmt.Fprintf(h, "(%d:%s%d:%s)", len(parts[i].name), parts[i].name, len(parts[i].value), parts[i].value)
		if err != nil {
			return nil
		}
	}
	grip := sha1.Sum(h.Bytes())
	return &grip
}

